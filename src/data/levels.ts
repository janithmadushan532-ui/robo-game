export function getLevelDef(levelNumber: number): BossLevelDef {
  const found = BOSS_LEVELS.find((l) => l.level === levelNumber);
  if (found) return found;
  const base = BOSS_LEVELS[(levelNumber - 1) % BOSS_LEVELS.length];
  const scaleFactor = 1 + (levelNumber - BOSS_LEVELS.length) * 0.14;
  return {
    ...base,
    level: levelNumber,
    id: `boss_tier_${levelNumber}`,
    bossName: `${base.bossName} MK-${levelNumber - BOSS_LEVELS.length + 1}`,
    maxHp: Math.round(base.maxHp * scaleFactor),
    attackPower: Math.round(base.attackPower * scaleFactor),
    aggression: Math.min(1, base.aggression + 0.04),
    rewardCoins: Math.round(base.rewardCoins * scaleFactor),
  };
}
