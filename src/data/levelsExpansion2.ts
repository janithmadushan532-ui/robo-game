function unit(
  name: string,
  nameSi: string,
  roleClass: string,
  monsterCategory: MonsterCategory,
  archetype: BossArchetype,
  aiStyle: AiBehaviorStyle,
  maxHp: number,
  attackPower: number,
  speed: number,
  primaryColor: number,
  secondaryColor: number,
  emissiveColor: number,
  scale: number,
  signaturePowers: MonsterPowerId[],
  opts?: Partial<EnemyUnitSpec>,
): EnemyUnitSpec {
  return {
    name,
    nameSi,
    roleClass,
    monsterCategory,
    archetype,
    aiStyle,
    maxHp,
    attackPower,
    speed,
    aggression: opts?.aggression ?? 0.9,
    blockChance: opts?.blockChance ?? 0.34,
    dodgeChance: opts?.dodgeChance ?? 0.25,
    primaryColor,
    secondaryColor,
    emissiveColor,
    scale,
    signaturePowers,
    hasPhases: opts?.hasPhases,
  };
}

interface SoloCfg {
  level: number;
  sector: 8 | 9 | 10 | 11;
  id: string;
  bossName: string;
  bossTitleSi: string;
  robotClass: string;
  monsterCategory: MonsterCategory;
  archetype: BossArchetype;
  aiStyle: AiBehaviorStyle;
  arenaTheme: ArenaTheme;
  arenaName: string;
  arenaNameSi: string;
  maxHp: number;
  attackPower: number;
  speed: number;
  primaryColor: number;
  secondaryColor: number;
  emissiveColor: number;
  scale: number;
  signaturePowers: MonsterPowerId[];
  loreSi: string;
  rewardCoins: number;
  isBossLevel?: boolean;
  hasPhases?: boolean;
  challengeLabel?: string;
  guaranteedPowerReward?: PowerId;
  aggression?: number;
  blockChance?: number;
  dodgeChance?: number;
}

function soloLevel(c: SoloCfg): BossLevelDef {
  return {
    level: c.level,
    sector: c.sector,
    id: c.id,
    bossName: c.bossName,
    bossTitleSi: c.bossTitleSi,
    robotClass: c.robotClass,
    monsterCategory: c.monsterCategory,
    isBossLevel: c.isBossLevel,
    challengeLabel: c.challengeLabel,
    archetype: c.archetype,
    aiStyle: c.aiStyle,
    arenaTheme: c.arenaTheme,
    arenaName: c.arenaName,
    arenaNameSi: c.arenaNameSi,
    maxHp: c.maxHp,
    attackPower: c.attackPower,
    speed: c.speed,
    aggression: c.aggression ?? (c.isBossLevel ? 0.98 : 0.92),
    blockChance: c.blockChance ?? 0.36,
    dodgeChance: c.dodgeChance ?? 0.28,
    primaryColor: c.primaryColor,
    secondaryColor: c.secondaryColor,
    emissiveColor: c.emissiveColor,
    scale: c.scale,
    signaturePowers: c.signaturePowers,
    enemies: c.hasPhases
      ? [
          unit(
            c.bossName,
            c.bossTitleSi,
            c.robotClass,
            c.monsterCategory,
            c.archetype,
            c.aiStyle,
            c.maxHp,
            c.attackPower,
            c.speed,
            c.primaryColor,
            c.secondaryColor,
            c.emissiveColor,
            c.scale,
            c.signaturePowers,
            {
              aggression: c.aggression ?? 0.98,
              blockChance: c.blockChance ?? 0.4,
              dodgeChance: c.dodgeChance ?? 0.28,
              hasPhases: true,
            },
          ),
        ]
      : undefined,
    loreSi: c.loreSi,
    rewardCoins: c.rewardCoins,
    guaranteedPowerReward: c.guaranteedPowerReward,
  };
}

interface MultiCfg {
  level: number;
  sector: 8 | 9 | 10 | 11;
  id: string;
  bossName: string;
  bossTitleSi: string;
  robotClass: string;
  monsterCategory: MonsterCategory;
  arenaTheme: ArenaTheme;
  arenaName: string;
  arenaNameSi: string;
  enemies: EnemyUnitSpec[];
  survivalWaves?: EnemyUnitSpec[][];
  loreSi: string;
  rewardCoins: number;
  challengeLabel: string;
  isBossLevel?: boolean;
  isSurvivalLevel?: boolean;
  guaranteedPowerReward?: PowerId;
}

function multiLevel(c: MultiCfg): BossLevelDef {
  const wave1Hp = c.enemies.reduce((s, e) => s + e.maxHp, 0);
  const laterWavesHp = (c.survivalWaves ?? []).reduce(
    (sum, w) => sum + w.reduce((ws, e) => ws + e.maxHp, 0),
    0,
  );
  const lead = c.enemies[0];
  return {
    level: c.level,
    sector: c.sector,
    id: c.id,
    bossName: c.bossName,
    bossTitleSi: c.bossTitleSi,
    robotClass: c.robotClass,
    monsterCategory: c.monsterCategory,
    isBossLevel: c.isBossLevel,
    isSurvivalLevel: c.isSurvivalLevel,
    challengeLabel: c.challengeLabel,
    archetype: lead.archetype,
    aiStyle: lead.aiStyle,
    arenaTheme: c.arenaTheme,
    arenaName: c.arenaName,
    arenaNameSi: c.arenaNameSi,
    maxHp: wave1Hp + laterWavesHp,
    attackPower: Math.max(...c.enemies.map((e) => e.attackPower)),
    speed: Math.max(...c.enemies.map((e) => e.speed)),
    aggression: 0.96,
    blockChance: lead.blockChance,
    dodgeChance: lead.dodgeChance,
    primaryColor: lead.primaryColor,
    secondaryColor: lead.secondaryColor,
    emissiveColor: lead.emissiveColor,
    scale: lead.scale,
    signaturePowers: lead.signaturePowers,
    enemies: c.enemies,
    survivalWaves: c.survivalWaves,
    loreSi: c.loreSi,
    rewardCoins: c.rewardCoins,
    guaranteedPowerReward: c.guaranteedPowerReward,
  };
}

